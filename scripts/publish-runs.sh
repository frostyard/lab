#!/usr/bin/env bash
# Publish the run data to the orphan branch `data/runs` of frostyard/lab.
#
# The publish-results CronWorkflow (manifests/publish-results.yaml) runs this
# from the root of a shallow clone of frostyard/lab whose `origin` URL can
# push. It regenerates runs.json from cluster state with
# scripts/collect_runs.py and commits it as the only file at the root of
# `data/runs`. The Pages workflow reads runs.json from that branch at build
# time.
#
# Why a data branch: the default branch accepts changes only through a pull
# request with the required check, so a direct push of run data to it is
# rejected. This script never pushes to main: its only push refspec is
# HEAD:refs/heads/data/runs, never forced.
#
# Environment:
#   RUNS_COLLECTOR  optional path of an executable that takes the output path
#                   as its only argument (tests use it instead of the cluster
#                   collector).
set -euo pipefail

readonly DATA_BRANCH=data/runs
readonly MAX_ATTEMPTS=3

script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
repo_root=$(dirname "${script_dir}")

# The URL holds a token in the pod: never print it.
remote_url=$(git remote get-url origin)

# Run git; on failure, print its stderr with any URL credentials masked.
git_masked() {
  local err rc=0
  err=$(mktemp)
  git "$@" 2>"${err}" || rc=$?
  if (( rc != 0 )); then
    sed -E 's#(://)[^/@[:space:]]+@#\1***@#g' "${err}" >&2
  fi
  rm -f "${err}"
  return "${rc}"
}

collect() {
  if [[ -n "${RUNS_COLLECTOR:-}" ]]; then
    "${RUNS_COLLECTOR}" "$1"
  else
    python3 "${repo_root}/scripts/collect_runs.py" "$1"
  fi
}

work=""
cleanup() {
  if [[ -n "${work}" ]]; then
    rm -rf "${work}"
    work=""
  fi
}
trap cleanup EXIT

attempt=0
while :; do
  attempt=$((attempt + 1))

  # A fresh work repo for each attempt, so a commit from a rejected attempt
  # can never stack under the next one.
  cleanup
  work=$(mktemp -d)
  git -C "${work}" init -q
  git -C "${work}" config user.name "frostyard-lab[bot]"
  git -C "${work}" config user.email "lab@frostyard.invalid"

  rc=0
  git_masked -C "${work}" ls-remote --exit-code "${remote_url}" \
    "refs/heads/${DATA_BRANCH}" >/dev/null || rc=$?
  case "${rc}" in
    0)
      branch_exists=1
      git_masked -C "${work}" fetch -q --depth 1 "${remote_url}" \
        "refs/heads/${DATA_BRANCH}"
      git -C "${work}" checkout -q --detach FETCH_HEAD
      ;;
    2)
      # First run: the empty work repo makes an orphan root commit. The
      # collector regenerates runs.json entirely from cluster state, so no
      # seed copy is needed.
      branch_exists=0
      echo "${DATA_BRANCH} does not exist yet; creating it as an orphan branch."
      ;;
    *)
      echo "ERROR: git ls-remote for ${DATA_BRANCH} failed (exit ${rc}); cannot publish." >&2
      exit 1
      ;;
  esac

  collect "${work}/runs.json"

  if (( branch_exists )); then
    # `generated` changes every run, so committing unconditionally would push
    # an empty-signal commit every 30 minutes forever. Compare everything else
    # and skip when only the timestamp moved.
    if git -C "${work}" diff --quiet -- runs.json; then
      echo "No change in run data; skipping commit."
      exit 0
    fi
    changed=$(git -C "${work}" diff -- runs.json \
                | grep -E '^[+-]' | grep -vE '^[+-]{3}' \
                | grep -vE '"generated"' | head -1 || true)
    if [[ -z "${changed}" ]]; then
      echo "Only the generation timestamp changed; skipping commit."
      exit 0
    fi
  fi

  git -C "${work}" add runs.json
  git -C "${work}" commit -q \
    -m "chore(report): refresh run data" \
    -m "Generated by the publish-results CronWorkflow on the lab k3s cluster."

  if git_masked -C "${work}" push -q "${remote_url}" "HEAD:refs/heads/${DATA_BRANCH}"; then
    echo "Published to ${DATA_BRANCH}."
    exit 0
  fi

  # The branch moved between the fetch and the push (or another run created
  # it). Recover by REGENERATING on top of the new tip rather than rebasing:
  # runs.json is derived entirely from cluster state, so regeneration is the
  # correct merge by construction.
  if (( attempt >= MAX_ATTEMPTS )); then
    echo "push rejected ${attempt}x; leaving it for the next cycle" >&2
    exit 1
  fi
  echo "push rejected (${DATA_BRANCH} moved); regenerating on top of the new tip" >&2
done
